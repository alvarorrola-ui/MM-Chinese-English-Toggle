#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from pypinyin import Style, pinyin

GLYPH_SIZE = 128
GLYPH_BYTES = GLYPH_SIZE * GLYPH_SIZE // 2
PINYIN_GLYPH_CHARS = "abcdefghijklmnopqrstuvwxyz12345"


def pack_i4(character: str, font: ImageFont.FreeTypeFont) -> bytes:
    image = Image.new("L", (GLYPH_SIZE, GLYPH_SIZE), 0)
    draw = ImageDraw.Draw(image)
    bbox = draw.textbbox((0, 0), character, font=font)
    width = bbox[2] - bbox[0]
    height = bbox[3] - bbox[1]
    x = (GLYPH_SIZE - width) // 2 - bbox[0]
    y = (GLYPH_SIZE - height) // 2 - bbox[1]
    draw.text((x, y), character, fill=255, font=font)
    pixels = list(image.getdata())
    output = bytearray(GLYPH_BYTES)
    for index in range(0, len(pixels), 2):
        output[index // 2] = ((pixels[index] >> 4) << 4) | (pixels[index + 1] >> 4)
    return bytes(output)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cnmod-root", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    root = args.cnmod_root.resolve()
    texts = []
    for name in ("mm_text_cn.reviewed.txt", "mm_text_cn.supplemental.txt"):
        path = root / name
        if path.exists():
            texts.append(path.read_text(encoding="utf-8"))
    if not texts:
        raise SystemExit(f"No translation text files found under {root}")

    characters = sorted(set(re.findall(r"[\u3400-\u9fff]", "\n".join(texts))))
    rows = []
    for character in characters:
        result = pinyin(character, style=Style.TONE3, heteronym=False, strict=False)
        if not result or not result[0]:
            continue
        syllable = result[0][0].lower()
        if re.fullmatch(r"[a-zv]+[1-5]?", syllable):
            rows.append((ord(character), syllable))

    font_candidates = [
        Path(r"C:\Windows\Fonts\arialbd.ttf"),
        Path(r"C:\Windows\Fonts\segoeuib.ttf"),
        Path(r"C:\Windows\Fonts\tahomabd.ttf"),
    ]
    font_path = next((candidate for candidate in font_candidates if candidate.exists()), None)
    if font_path is None:
        raise SystemExit("No supported Windows font found for pinyin glyph rendering.")
    font = ImageFont.truetype(str(font_path), 104)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as output:
        output.write("/* Generated by tools/generate_pinyin.py; I4 atlas includes tone digits. */\n")
        output.write("static const CnPinyinEntry gCnPinyinEntries[] = {\n")
        for codepoint, syllable in rows:
            output.write(f'    {{ 0x{codepoint:04X}, "{syllable}" }},\n')
        output.write("};\n\n")
        output.write(f'static const char gCnPinyinGlyphCharacters[] = "{PINYIN_GLYPH_CHARS}";\n')
        output.write(f"static const u8 gCnPinyinGlyphBitmaps[{len(PINYIN_GLYPH_CHARS)}][{GLYPH_BYTES}] = {{\n")
        for character in PINYIN_GLYPH_CHARS:
            bitmap = pack_i4(character, font)
            output.write("    {\n")
            for offset in range(0, len(bitmap), 16):
                row = bitmap[offset:offset + 16]
                output.write("        " + ", ".join(f"0x{value:02X}" for value in row) + ",\n")
            output.write("    },\n")
        output.write("};\n")

    print(f"Generated pinyin for {len(rows)} Hanzi and {len(PINYIN_GLYPH_CHARS)} Latin/digit glyphs.")


if __name__ == "__main__":
    main()
